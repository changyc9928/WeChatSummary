export function createT(lang) {
  const dict = translations[lang] || translations.en;
  return (key, params = {}) => {
    let str = dict[key] ?? key;
    Object.entries(params).forEach(([k, v]) => {
      str = str.split(`{${k}}`).join(String(v));
    });
    return str;
  };
}